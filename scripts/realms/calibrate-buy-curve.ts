/**
 * Measure each Realms title's Buy Bonus value per spin at every purchasable
 * quantity and write src/lib/realms/buy-curve.ts.
 *
 * A bought session's multiplier applies once to the whole session, so a spin
 * is worth more in a longer session. The curve stores the fair per-spin price
 * (× bet) for quantity 1…maxFsSessionSpins so any purchase returns TARGET_RTP.
 *
 *   npx tsx scripts/realms/calibrate-buy-curve.ts --shard 0/11
 *   npx tsx scripts/realms/calibrate-buy-curve.ts --merge 11
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { REALMS_GAMES, realmsDefaultConfig, type RealmsGameDef } from "../../src/lib/realms";
import { TARGET_RTP } from "../../src/lib/realms/defaults";
import { remainingFreeSpinsAfterSpin } from "../../src/lib/realms/schema";
import { finalizeFreeSpinTotal } from "../../src/components/maxhigh/realms/engine/multiplierEngine";
import { resolveSpin } from "../../src/components/maxhigh/realms/engine/spinResolver";
import { createEngineCtx } from "../../src/components/maxhigh/realms/engine/types";
import { mulberry32 } from "../realms-sim";

const ROOT = path.resolve(import.meta.dirname, "../..");
const SHARD_DIR = path.join(os.tmpdir(), "realms-buy-curve");
const OUT = path.join(ROOT, "src/lib/realms/buy-curve.ts");
/** Quantities measured directly; the rest are interpolated. */
const SAMPLE_QS = [1, 2, 3, 4, 6, 8, 10, 12, 15, 20, 25, 30];
const SPIN_BUDGET = 900_000;

function valuePerSpin(def: RealmsGameDef, q: number, seed: number): number {
  const cfg = realmsDefaultConfig(def.id);
  const ctx = createEngineCtx(cfg, def.board, mulberry32(seed));
  const features = Math.max(3000, Math.min(60_000, Math.ceil(SPIN_BUDGET / SAMPLE_QS.length / q)));
  let paid = 0;
  for (let f = 0; f < features; f++) {
    let left = q;
    let played = 0;
    let win = 0;
    let bomb = 0;
    while (left > 0) {
      const s = resolveSpin(ctx, {
        bet: 1,
        ante: false,
        isFreeSpins: true,
        initialBombAccumulator: bomb,
      });
      win = +(win + s.totalWin).toFixed(2);
      bomb = s.bombAccumulator;
      played += 1;
      left = remainingFreeSpinsAfterSpin({
        leftBefore: left,
        retrigger: s.retriggerSpins,
        playedAfter: played,
        maxSessionSpins: cfg.maxFsSessionSpins,
      });
    }
    paid += Math.min(finalizeFreeSpinTotal(cfg, win, bomb), cfg.maxWinMult);
  }
  return paid / features / q;
}

/** Pool-adjacent-violators: the closest non-decreasing fit to noisy samples. */
function isotonic(values: number[], weights: number[]): number[] {
  const blocks = values.map((v, i) => ({ v, w: weights[i]!, n: 1 }));
  for (let i = 0; i < blocks.length - 1;) {
    if (blocks[i]!.v > blocks[i + 1]!.v) {
      const a = blocks[i]!;
      const b = blocks[i + 1]!;
      const w = a.w + b.w;
      blocks.splice(i, 2, { v: (a.v * a.w + b.v * b.w) / w, w, n: a.n + b.n });
      if (i > 0) i -= 1;
    } else i += 1;
  }
  return blocks.flatMap((b) => Array<number>(b.n).fill(b.v));
}

function curveFor(def: RealmsGameDef): number[] {
  const t0 = Date.now();
  const maxQ = realmsDefaultConfig(def.id).maxFsSessionSpins;
  const qs = SAMPLE_QS.filter((q) => q <= maxQ);
  if (qs[qs.length - 1] !== maxQ) qs.push(maxQ);
  const raw = qs.map((q, i) => valuePerSpin(def, q, def.no * 104_729 + i));
  const fit = isotonic(
    raw,
    qs.map((q) => q),
  );
  const curve: number[] = [];
  for (let q = 1; q <= maxQ; q++) {
    const j = qs.findIndex((x) => x >= q);
    const v =
      qs[j] === q || j === 0
        ? fit[j]!
        : fit[j - 1]! + ((fit[j]! - fit[j - 1]!) * (q - qs[j - 1]!)) / (qs[j]! - qs[j - 1]!);
    curve.push(Math.max(0.05, Math.round(v / TARGET_RTP / 0.05) * 0.05));
  }
  const fixed = curve.map((c) => +c.toFixed(2));
  console.log(
    `${String(def.no).padStart(2)} ${def.id.padEnd(22)} q1 ${fixed[0]}× q${def.freeSpins} ${fixed[def.freeSpins - 1]}× q${maxQ} ${fixed[maxQ - 1]}× (${((Date.now() - t0) / 1000).toFixed(0)}s)`,
  );
  return fixed;
}

function write(entries: [string, number[]][]) {
  const byId = new Map(entries);
  const lines = REALMS_GAMES.map((g) => {
    const c = byId.get(g.id);
    if (!c) throw new Error(`missing curve for ${g.id}`);
    return `  "${g.id}": [${c.join(", ")}],`;
  });
  fs.writeFileSync(
    OUT,
    `/**
 * GENERATED by scripts/realms/calibrate-buy-curve.ts — do not edit by hand.
 * Fair Buy Bonus price per free spin (× bet) for quantity 1, 2, 3 … (index = quantity − 1),
 * measured with the calibrated default math. Re-run after recalibrating.
 */
export const REALMS_BUY_CURVE: Record<string, number[]> = {
${lines.join("\n")}
};
`,
  );
  console.log(`wrote ${path.relative(ROOT, OUT)} (${lines.length} titles)`);
}

const args = process.argv.slice(2);
if (args[0] === "--shard") {
  const [i, n] = args[1]!.split("/").map(Number);
  const out = REALMS_GAMES.filter((g) => (g.no - 1) % n! === i).map(
    (g) => [g.id, curveFor(g)] as [string, number[]],
  );
  fs.mkdirSync(SHARD_DIR, { recursive: true });
  fs.writeFileSync(path.join(SHARD_DIR, `shard-${i}.json`), JSON.stringify(out));
} else if (args[0] === "--merge") {
  const all: [string, number[]][] = [];
  for (let i = 0; i < Number(args[1]); i++)
    all.push(
      ...(JSON.parse(fs.readFileSync(path.join(SHARD_DIR, `shard-${i}.json`), "utf8")) as [
        string,
        number[],
      ][]),
    );
  write(all);
} else {
  write(REALMS_GAMES.map((g) => [g.id, curveFor(g)] as [string, number[]]));
}
