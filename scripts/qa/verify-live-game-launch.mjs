import fs from 'node:fs';
import assert from 'node:assert/strict';
const tabs = await (await fetch('http://127.0.0.1:9231/json')).json();
const ws = new WebSocket(tabs.find(t => t.type === 'page').webSocketDebuggerUrl);
let seq = 0; const pending = new Map();
ws.onmessage = ({ data }) => { const m = JSON.parse(data); if (m.id) { const p = pending.get(m.id); pending.delete(m.id); m.error ? p.reject(Error(m.error.message)) : p.resolve(m.result); } };
await new Promise(resolve => { ws.onopen = resolve; });
const send = (method, params = {}) => new Promise((resolve, reject) => { const id = ++seq; pending.set(id, { resolve, reject }); ws.send(JSON.stringify({ id, method, params })); });
const evaluate = async expression => (await send('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true })).result.value;
async function waitFor(expression, limit = 150) { for (let i = 0; i < limit; i++) { if (await evaluate(expression).catch(() => false)) return true; await new Promise(resolve => setTimeout(resolve, 100)); } return false; }
await send('Fetch.disable');
await send('Page.enable');
await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: false });
await send('Page.navigate', { url: 'http://localhost:8080/' });
const cookies = await send('Network.getCookies', { urls: ['http://localhost:8080/'] });
assert(cookies.cookies.some(cookie => cookie.name === 'mh_session'), 'A signed-in demo session is required');
assert(await waitFor(`!!document.querySelector('button[aria-label="Play Fortune Rabbit"]')`));
await new Promise(resolve => setTimeout(resolve, 3000));
await evaluate(`document.querySelector('button[aria-label="Play Fortune Rabbit"]').click()`);
assert(await waitFor(`!![...document.querySelectorAll('[role="dialog"] button')].find(b => /^play now$/i.test(b.textContent.trim()))`));
await evaluate(`[...document.querySelectorAll('[role="dialog"] button')].find(b => /^play now$/i.test(b.textContent.trim())).click()`);
const splashSeen = await waitFor(`!!document.querySelector('[data-game-boot="fortune-rabbit"]')`);
if (!splashSeen) console.log(await evaluate(`JSON.stringify({text:document.body.innerText.slice(-1200),dialogs:[...document.querySelectorAll('[role=dialog]')].map(d=>({label:d.getAttribute('aria-label'),text:d.innerText.slice(0,300)}))})`));
assert(splashSeen, 'The game splash did not appear');
const screenshot = await send('Page.captureScreenshot', { format: 'png' });
fs.writeFileSync('output/loading-screen-review/live-fortune-rabbit.png', Buffer.from(screenshot.data, 'base64'));
const opened = await waitFor(`!!document.querySelector('[aria-label="Fortune Rabbit game"]') && !document.querySelector('[data-game-boot]')`, 300);
assert(opened, 'The splash did not transition into play');
const result = { game: 'fortune-rabbit', signedInLaunch: true, splashSeen, transitionedToGame: opened, placedBets: false };
fs.writeFileSync('output/loading-screen-review/live-launch.json', JSON.stringify(result, null, 2));
await evaluate(`document.querySelector('[aria-label="Close game"]').click()`);
console.log(JSON.stringify(result));
ws.close();
