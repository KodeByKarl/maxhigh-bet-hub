// Deterministic PROPOSAL of 50 available / 50 locked games for OWNER REVIEW. It is NOT the active configuration and nothing reads it
// at runtime. Rule (arbitrary, stated openly): keep the catalog's category mix (41 slots / 4 fishing / 5 cards available) and,
// within each category, take the first N in catalog order as available. The contract, not this script, decides the real list.
//   node scripts/qa/make-game-allocation.mjs <outDir> [testPolicyFile]
import fs from "node:fs";
import path from "node:path";

const out = process.argv[2] ?? "deploy/handoff";
const rows = fs.readFileSync("deploy/diagnostics/uat-game-catalog.tsv", "utf8").trim().split("\n").slice(1).map((l) => {
  const [id, category, title] = l.split("\t"); return { id, category, title };
});
if (rows.length !== 100) throw new Error(`catalog has ${rows.length} games, expected 100`);
const AVAILABLE = { slot: 41, fishing: 4, cards: 5 };
const byCat = {};
for (const r of rows) (byCat[r.category] ??= []).push(r);
const available = [], locked = [];
for (const [cat, list] of Object.entries(byCat)) {
  if (AVAILABLE[cat] === undefined) throw new Error("unexpected category " + cat);
  list.forEach((g, i) => (i < AVAILABLE[cat] ? available : locked).push(g));
}
if (available.length !== 50 || locked.length !== 50) throw new Error(`split is ${available.length}/${locked.length}`);

const proposal = {
  status: "PROPOSED - REQUIRES OWNER CONFIRMATION - NOT ACTIVE",
  rule: "category mix preserved (41 slot / 4 fishing / 5 cards available); first N per category in catalog order",
  generatedFrom: "deploy/diagnostics/uat-game-catalog.tsv",
  counts: { available: available.length, locked: locked.length, total: rows.length },
  perCategory: Object.fromEntries(Object.keys(byCat).map((c) => [c, { total: byCat[c].length, available: available.filter((g) => g.category === c).length, locked: locked.filter((g) => g.category === c).length }])),
  available: available.map((g) => g.id), locked: locked.map((g) => g.id),
};
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, "PROPOSED_GAME_ALLOCATION.json"), JSON.stringify(proposal, null, 1));
const md = [
  "# Proposed game allocation - 50 available / 50 locked",
  "",
  "**Status: PROPOSED. REQUIRES OWNER CONFIRMATION. NOT ACTIVE.** Generated by `scripts/qa/make-game-allocation.mjs`; the active policy file (`src/server/policy/access-policy.config.ts`) is unchanged and ships with no locks.",
  "",
  "Rule (arbitrary by design): preserve the catalog category mix and take the first N games per category in catalog order as available. Which 50 games the client is entitled to is a commercial fact that this proposal does not know.",
  "",
  "| Category | Total | Available | Locked |", "|---|---|---|---|",
  ...Object.entries(proposal.perCategory).map(([c, v]) => `| ${c} | ${v.total} | ${v.available} | ${v.locked} |`),
  "", "## Available (50)", "", ...available.map((g, i) => `${i + 1}. \`${g.id}\` - ${g.title} (${g.category})`),
  "", "## Locked (50)", "", ...locked.map((g, i) => `${i + 1}. \`${g.id}\` - ${g.title} (${g.category})`), "",
];
fs.writeFileSync(path.join(out, "PROPOSED_GAME_ALLOCATION.md"), md.join("\n"));
if (process.argv[3]) {   // test-only policy for disposable end-to-end runs: uses the proposal, NEVER shipped
  const { publicKeyPem } = JSON.parse(fs.readFileSync(path.join(path.dirname(process.argv[3]), "test-grant-key.json"), "utf8"));
  fs.writeFileSync(process.argv[3], JSON.stringify({ version: 1, environment: "uat", gameLocks: { enforcement: "on", lockedGames: proposal.locked },
    clientAccounts: { enforcement: "on", maxClientAccounts: 2 }, grantKeys: [{ id: "test-key-1", publicKeyPem }] }, null, 1));
}
console.log(JSON.stringify(proposal.counts), JSON.stringify(proposal.perCategory));
